"""
Permissions & Dispatch Messages
Định nghĩa danh mục các lý do thẩm quyền phục vụ giao tiếp giữa PermissionService và TV2 Worker.
"""
from enum import StrEnum


class DispatchReason(StrEnum):
    """Mã lý do thẩm định dispatch lệnh (không tự đổi lệnh hay tự commit DB)."""
    # Các trường hợp hợp lệ (allowed=True)
    AUTHORIZED = "AUTHORIZED"
    AUTHORIZED_FIRST_APPLY = "AUTHORIZED_FIRST_APPLY"
    AUTHORIZED_APPLIED_CONFIG = "AUTHORIZED_APPLIED_CONFIG"

    # Các trường hợp từ chối liên quan đến lệnh và thiết bị (allowed=False)
    COMMAND_NOT_PERSISTED = "COMMAND_NOT_PERSISTED"
    INVALID_COMMAND_IDENTIFIER = "INVALID_COMMAND_IDENTIFIER"
    UNSUPPORTED_SOURCE = "UNSUPPORTED_SOURCE"
    DEVICE_NOT_FOUND = "DEVICE_NOT_FOUND"
    UNKNOWN_COMMAND_TYPE = "UNKNOWN_COMMAND_TYPE"

    # Các trường hợp từ chối liên quan đến cấu hình (APPLY_CONFIG)
    CONFIG_VERSION_MISSING = "CONFIG_VERSION_MISSING"
    CONFIG_NOT_FOUND = "CONFIG_NOT_FOUND"
    CONFIG_AUTHOR_MISSING = "CONFIG_AUTHOR_MISSING"
    AUTHOR_INACTIVE = "AUTHOR_INACTIVE"
    AUTHOR_PERMISSION_DENIED = "AUTHOR_PERMISSION_DENIED"
    AUTHOR_SCOPE_DENIED = "AUTHOR_SCOPE_DENIED"
    AUTHOR_SCOPE_EXPIRED = "AUTHOR_SCOPE_EXPIRED"

    # Các trường hợp từ chối liên quan đến lệnh điều khiển thủ công (SET_MODE, SET_FAN)
    MISSING_USER_OR_SESSION = "MISSING_USER_OR_SESSION"
    USER_INACTIVE = "USER_INACTIVE"
    SESSION_NOT_FOUND = "SESSION_NOT_FOUND"
    SESSION_REVOKED = "SESSION_REVOKED"
    SESSION_EXPIRED = "SESSION_EXPIRED"
    TOKEN_VERSION_MISMATCH = "TOKEN_VERSION_MISMATCH"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    SCOPE_DENIED = "SCOPE_DENIED"
    SCOPE_EXPIRED = "SCOPE_EXPIRED"
    SYSTEM_CONTROL_NOT_PERMITTED = "SYSTEM_CONTROL_NOT_PERMITTED"
